"""Our own ingredient dictionary (en/es/fr/de/it/pt) - free, instant, no AI.
Data: data/ingredient_dictionary.json (generated by scripts/build_ingredient_dictionary.py)."""
import json
import re
import unicodedata
from pathlib import Path
from typing import Optional

_FILE = Path(__file__).resolve().parent.parent / "data" / "ingredient_dictionary.json"
LANGS = {"en": "English", "es": "Spanish", "fr": "French", "de": "German", "it": "Italian", "pt": "Portuguese"}
_CONCEPTS = None
_INDEX = None   # normalised term -> (concept index, language)


def _norm(text: str) -> str:
    t = unicodedata.normalize("NFKD", text.lower())
    t = "".join(c for c in t if not unicodedata.combining(c))
    t = t.replace("œ", "oe").replace("ß", "ss")
    return re.sub(r"[^a-z0-9 ]+", " ", t).strip()


def _load():
    global _CONCEPTS, _INDEX
    if _CONCEPTS is not None:
        return
    try:
        _CONCEPTS = json.load(open(_FILE, encoding="utf-8"))
    except Exception:
        _CONCEPTS = []
    _INDEX = {}
    for i, c in enumerate(_CONCEPTS):
        _INDEX.setdefault(_norm(c["en"]), (i, "en"))
        for lang in ("es", "fr", "de", "it", "pt"):
            for term in c.get(lang, []):
                _INDEX.setdefault(_norm(term), (i, lang))


def _variants(t: str):
    yield t
    if t.endswith("es"):
        yield t[:-2]
    if t.endswith("s"):
        yield t[:-1]
    if t.endswith("en") or t.endswith("er"):      # German plurals: kartoffeln, zwiebeln, eier
        yield t[:-2]
    if t.endswith("n") or t.endswith("e"):
        yield t[:-1]
    yield t + "s"


def lookup(text: str) -> Optional[dict]:
    """Return {'concept': {...}, 'language': 'es', 'matched': 'pollo'} or None.
    Exact match first; otherwise the longest dictionary term appearing as whole words (e.g. 'pechuga de pollo deshuesada')."""
    _load()
    if not _CONCEPTS or not text:
        return None
    t = _norm(text)
    if not t:
        return None
    for v in _variants(t):
        if v in _INDEX:
            i, lang = _INDEX[v]
            return {"concept": _CONCEPTS[i], "language": lang, "matched": v}
    padded = f" {t} "
    best = None
    for term, (i, lang) in _INDEX.items():
        if len(term) >= 4 and f" {term} " in padded and (best is None or len(term) > len(best[0])):
            best = (term, i, lang)
    if best:
        return {"concept": _CONCEPTS[best[1]], "language": best[2], "matched": best[0]}
    return None


def to_english(text: str) -> Optional[str]:
    hit = lookup(text)
    return hit["concept"]["en"] if hit else None


def to_language(english_name: str, lang: str) -> Optional[str]:
    """English ingredient -> name in lang (first synonym), or None."""
    hit = lookup(english_name)
    if not hit or lang == "en":
        return english_name if lang == "en" else None
    terms = hit["concept"].get(lang)
    return terms[0] if terms else None


def alternatives(concept: dict, exclude_lang: str = "", limit: int = 5) -> list:
    out = []
    for lang in ("en", "es", "fr", "de", "it", "pt"):
        if lang == exclude_lang:
            continue
        terms = [concept["en"]] if lang == "en" else concept.get(lang, [])
        for t in terms:
            if t not in out and _norm(t) != _norm(concept["en"]):
                out.append(t)
    return out[:limit]
